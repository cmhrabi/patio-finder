/**
 * Reads tokens.json (canonical) and emits:
 *   src/tokens/tokens.css — CSS custom properties under :root, [data-theme=cream], [data-theme=map],
 *                           plus [data-card-style=...] modifiers.
 *   src/tokens/tokens.ts  — typed constants mirroring the same values.
 *
 * Run via `pnpm tokens:gen`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const tokens = JSON.parse(readFileSync(resolve(ROOT, "tokens.json"), "utf8"));

type Type = {
  size: string;
  lineHeight: string;
  tracking: string;
  family: "display" | "body" | "mono";
  weight: number;
  transform?: string;
  features?: string;
};

const colorVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");

const spaceVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --space-${k}: ${v};`)
    .join("\n");

const radiusVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --radius-${k}: ${v};`)
    .join("\n");

const shadowVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --shadow-${k}: ${v};`)
    .join("\n");

const fontVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --font-${k}: ${v};`)
    .join("\n");

const themeVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --theme-${k}: ${v};`)
    .join("\n");

const cardStyleVars = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  --card-${k}: ${v};`)
    .join("\n");

let css = `/* AUTO-GENERATED by scripts/generate-tokens.ts. Do not edit by hand.
 * Source of truth: tokens.json
 */

:root {
${colorVars(tokens.color)}

${spaceVars(tokens.space)}

${radiusVars(tokens.radius)}

${shadowVars(tokens.shadow)}

${fontVars(tokens.font)}
}

[data-theme="cream"] {
${themeVars(tokens.themes.cream)}
}

[data-theme="map"] {
${themeVars(tokens.themes.map)}
}
`;

for (const [name, vals] of Object.entries(tokens.cardStyle) as [string, Record<string, string>][]) {
  css += `\n[data-card-style="${name}"] {\n${cardStyleVars(vals)}\n}\n`;
}

// Type ramp utility classes (consumed by Heading/Eyebrow/etc).
css += `\n/* Type ramp */\n`;
for (const [name, t] of Object.entries(tokens.type) as [string, Type][]) {
  css += `.type-${name} {
  font-family: var(--font-${t.family});
  font-size: ${t.size};
  line-height: ${t.lineHeight};
  letter-spacing: ${t.tracking};
  font-weight: ${t.weight};
${t.transform ? `  text-transform: ${t.transform};\n` : ""}${
    t.features ? `  font-feature-settings: ${t.features};\n` : ""
  }}
`;
}

mkdirSync(resolve(ROOT, "src/tokens"), { recursive: true });
writeFileSync(resolve(ROOT, "src/tokens/tokens.css"), css);

// TypeScript constants
const tsHeader = `// AUTO-GENERATED by scripts/generate-tokens.ts. Do not edit by hand.
// Source of truth: tokens.json
`;

const renderObj = (record: Record<string, string>) =>
  Object.entries(record)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");

const renderTypeObj = (record: Record<string, Type>) =>
  Object.entries(record)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");

const ts = `${tsHeader}
export const color = {
${renderObj(tokens.color)}
} as const;
export type ColorToken = keyof typeof color;

export const space = {
${renderObj(tokens.space)}
} as const;
export type SpaceToken = keyof typeof space;

export const radius = {
${renderObj(tokens.radius)}
} as const;
export type RadiusToken = keyof typeof radius;

export const shadow = {
${renderObj(tokens.shadow)}
} as const;
export type ShadowToken = keyof typeof shadow;

export const font = {
${renderObj(tokens.font)}
} as const;
export type FontToken = keyof typeof font;

export const type = {
${renderTypeObj(tokens.type)}
} as const;
export type TypeToken = keyof typeof type;

export const themes = ${JSON.stringify(tokens.themes, null, 2)} as const;
export type ThemeName = keyof typeof themes;

export const cardStyles = ${JSON.stringify(tokens.cardStyle, null, 2)} as const;
export type CardStyleName = keyof typeof cardStyles;

/** Convenience: resolve a color token to its CSS var() reference. */
export const cssVar = {
  color: (k: ColorToken) => \`var(--\${k})\`,
  space: (k: SpaceToken) => \`var(--space-\${k})\`,
  radius: (k: RadiusToken) => \`var(--radius-\${k})\`,
  shadow: (k: ShadowToken) => \`var(--shadow-\${k})\`,
  font: (k: FontToken) => \`var(--font-\${k})\`,
};
`;

writeFileSync(resolve(ROOT, "src/tokens/tokens.ts"), ts);

// eslint-disable-next-line no-console
console.log("✔ Wrote src/tokens/tokens.css and src/tokens/tokens.ts");
